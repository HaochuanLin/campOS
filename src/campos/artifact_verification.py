"""Verify integrity of files recorded by a campOS quickstart manifest."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


SHA256_RE = re.compile(r"^[0-9a-f]{64}$")


def sha256_file(path: Path) -> str:
    """Return the SHA-256 digest of a file without loading it all into memory."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def verify_manifest(manifest_path: Path) -> tuple[list[str], list[str]]:
    """Return (verified artifact names, failures) for a quickstart manifest."""
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        return [], [f"cannot read manifest: {exc}"]
    if not isinstance(manifest, dict):
        return [], ["manifest root must be a JSON object"]
    artifacts = manifest.get("artifact_checksums")
    if not isinstance(artifacts, dict):
        return [], ["manifest has no artifact_checksums object"]
    verified: list[str] = []
    failures: list[str] = []
    root = manifest_path.resolve().parent
    for name, expected in sorted(artifacts.items()):
        if (
            not isinstance(name, str) or not name
            or name in {".", ".."} or "/" in name or "\\" in name
            or Path(name).name != name
        ):
            failures.append(f"unsafe artifact name: {name!r}")
            continue
        if not isinstance(expected, dict):
            failures.append(f"{name}: checksum record must be an object")
            continue
        expected_hash = expected.get("sha256")
        expected_size = expected.get("size_bytes")
        if not isinstance(expected_hash, str) or not SHA256_RE.fullmatch(expected_hash):
            failures.append(f"{name}: invalid SHA-256 value in manifest")
            continue
        if isinstance(expected_size, bool) or not isinstance(expected_size, int) or expected_size < 0:
            failures.append(f"{name}: invalid size_bytes value in manifest")
            continue
        path = root / name
        if path.is_symlink() or path.resolve().parent != root:
            failures.append(f"{name}: artifact must be a regular file beside the manifest")
            continue
        if not path.is_file():
            failures.append(f"{name}: artifact is missing")
            continue
        actual_size = path.stat().st_size
        actual_hash = sha256_file(path)
        if actual_size != expected_size:
            failures.append(f"{name}: size mismatch (expected {expected_size}, got {actual_size})")
            continue
        if actual_hash != expected_hash:
            failures.append(f"{name}: SHA-256 mismatch")
            continue
        verified.append(name)
    if not artifacts:
        failures.append("manifest contains no artifact checksums")
    return verified, failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest", required=True, type=Path,
        help="path to quickstart_manifest.json generated by campos-start",
    )
    args = parser.parse_args(argv)
    verified, failures = verify_manifest(args.manifest.expanduser())
    for name in verified:
        print(f"OK  {name}")
    for failure in failures:
        print(f"FAIL  {failure}", file=sys.stderr)
    if failures:
        print(f"Artifact verification failed: {len(failures)} issue(s).", file=sys.stderr)
        return 2
    print(f"Verified {len(verified)} artifact(s); SHA-256 and file sizes match.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
